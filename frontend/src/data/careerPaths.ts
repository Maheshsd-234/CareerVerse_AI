export const getExamInfo = (examName: string) => {
  const cleanName = examName.split("(")[0].trim();
  for (const [key, val] of Object.entries(EXAM_DETAILS)) {
    if (cleanName.toLowerCase().includes(key.toLowerCase()) || examName.toLowerCase().includes(key.toLowerCase())) {
      return { shortName: key, ...val };
    }
  }
  return {
    shortName: examName,
    fullName: examName,
    scope: "Competitive / College Entrance",
    description: `Entrance qualification exam for admission and specialized recruitment in this domain.`,
  };
};

